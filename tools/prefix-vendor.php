<?php
/**
 * Dev tool: vendor smalot/pdfparser into vendor/ under a private namespace.
 *
 * Copies the library installed by Composer in .dev/vendor/smalot/pdfparser
 * (src/ + LICENSE.txt) to vendor/smalot/pdfparser/ and rewrites the
 * namespace Smalot\PdfParser to HDS_Vendor\Smalot\PdfParser everywhere it
 * occurs: namespace declarations, use statements, fully-qualified names in
 * code and docblocks, and string literals (the library builds class names
 * dynamically, e.g. '\Smalot\PdfParser\Font\Font' . $subtype and
 * '\\Smalot\\PdfParser\\Encoding\\' . $name). A prefixed copy cannot clash
 * with another plugin that ships a different smalot version.
 *
 * Every vendored file also gets a direct-access guard right after its
 * namespace declaration and a notice that it was modified (LGPL-3.0 5a).
 * Finally it writes vendor/autoload.php (PSR-4 for HDS_Vendor\Smalot\PdfParser\
 * only) and vendor/README.md.
 *
 * Usage (from the plugin root, after `composer install`):
 *   php tools/prefix-vendor.php            Regenerate vendor/ and lint it.
 *   php tools/prefix-vendor.php --no-lint  Skip `php -l` of the output.
 *
 * Re-runnable: it deletes vendor/smalot/pdfparser/ (and nothing else) first.
 * symfony/polyfill-mbstring is intentionally NOT vendored: the plugin
 * requires the mbstring extension, and the script verifies that the library
 * does not reference Symfony classes.
 *
 * Never shipped (tools/ is in .distignore); refuses to run outside the CLI.
 *
 * @package SmartDocumentSearch
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

/**
 * Prefix used for every vendored namespace.
 */
const HDS_PV_PREFIX = 'HDS_Vendor';

/**
 * Expected library version (composer.json pins it).
 */
const HDS_PV_VERSION = '2.13.0';

/**
 * Print a message and stop with an error code.
 *
 * @param string $message Message.
 * @return void
 */
function hds_pv_fail( string $message ) {
	fwrite( STDERR, 'prefix-vendor: ERROR: ' . $message . PHP_EOL );
	exit( 1 );
}

/**
 * Print a progress line.
 *
 * @param string $message Message.
 * @return void
 */
function hds_pv_say( string $message ) {
	fwrite( STDOUT, $message . PHP_EOL );
}

/**
 * Recursively delete a directory that must live inside $guard.
 *
 * @param string $dir   Directory to delete.
 * @param string $guard Real path the directory must be inside of.
 * @return void
 */
function hds_pv_rmdir( string $dir, string $guard ) {
	if ( ! is_dir( $dir ) ) {
		return;
	}
	$real = realpath( $dir );
	if ( false === $real || 0 !== strpos( $real . '/', rtrim( $guard, '/' ) . '/' ) || $real === rtrim( $guard, '/' ) ) {
		hds_pv_fail( 'refusing to delete ' . $dir . ' (outside ' . $guard . ')' );
	}
	$items = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator( $real, FilesystemIterator::SKIP_DOTS ),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach ( $items as $item ) {
		if ( $item->isDir() && ! $item->isLink() ) {
			rmdir( $item->getPathname() );
		} else {
			unlink( $item->getPathname() );
		}
	}
	rmdir( $real );
}

/**
 * Rewrite every reference to the Smalot\PdfParser namespace.
 *
 * Matches the namespace with zero, one or two leading backslashes and with
 * single or doubled (string-escaped) separators, e.g.
 *   namespace Smalot\PdfParser;          use Smalot\PdfParser\Font;
 *   '\Smalot\PdfParser\Font\Font'        '\\Smalot\\PdfParser\\Encoding\\'
 *
 * @param string $code PHP source.
 * @return string
 */
function hds_pv_prefix( string $code ): string {
	return (string) preg_replace_callback(
		'/(?<![A-Za-z0-9_\\\\])(\\\\*)Smalot(\\\\+)PdfParser(?![A-Za-z0-9_])/',
		static function ( array $m ): string {
			return $m[1] . HDS_PV_PREFIX . $m[2] . 'Smalot' . $m[2] . 'PdfParser';
		},
		$code
	);
}

/**
 * Insert the direct-access guard and modification notice after the
 * namespace declaration.
 *
 * @param string $code     Prefixed PHP source.
 * @param string $relative File path for error messages.
 * @return string
 */
function hds_pv_guard( string $code, string $relative ): string {
	$guard = "\n// Modified for Smart Document Search: namespace prefixed with " . HDS_PV_PREFIX . '\\ by tools/prefix-vendor.php.'
		. "\nif ( ! \\defined( 'ABSPATH' ) ) {\n\texit;\n}\n";
	$count = 0;
	$code  = (string) preg_replace( '/^(namespace\s+' . HDS_PV_PREFIX . '\\\\Smalot\\\\PdfParser[A-Za-z0-9_\\\\]*\s*;[ \t]*\n)/m', '$1' . $guard, $code, 1, $count );
	if ( 1 !== $count ) {
		hds_pv_fail( 'no namespace declaration found in ' . $relative );
	}
	return $code;
}

/**
 * Contents of vendor/autoload.php.
 *
 * @return string
 */
function hds_pv_autoload_source(): string {
	return <<<'PHP'
<?php
/**
 * Autoloader for the vendored, namespace-prefixed third-party libraries.
 *
 * GENERATED by tools/prefix-vendor.php - do not edit by hand.
 * Loads only classes under HDS_Vendor\Smalot\PdfParser\ (PSR-4) from
 * vendor/smalot/pdfparser/src/Smalot/PdfParser/. Safe to include more than
 * once and alongside other plugins' Composer autoloaders.
 *
 * @package SmartDocumentSearch
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

if ( ! function_exists( 'hds_vendor_autoload' ) ) {
	/**
	 * PSR-4 autoloader for HDS_Vendor\Smalot\PdfParser\.
	 *
	 * Class names can come from PDF data (font subtypes), so only plain
	 * identifier segments are accepted: no path traversal is possible.
	 *
	 * @param string $class Fully-qualified class name.
	 * @return void
	 */
	function hds_vendor_autoload( $class ) {
		$prefix = 'HDS_Vendor\\Smalot\\PdfParser\\';
		$class  = ltrim( (string) $class, '\\' );
		if ( 0 !== strncmp( $class, $prefix, strlen( $prefix ) ) ) {
			return;
		}
		$relative = substr( $class, strlen( $prefix ) );
		if ( ! preg_match( '/^[A-Za-z_][A-Za-z0-9_]*(?:\\\\[A-Za-z_][A-Za-z0-9_]*)*$/D', $relative ) ) {
			return;
		}
		$file = __DIR__ . '/smalot/pdfparser/src/Smalot/PdfParser/' . str_replace( '\\', '/', $relative ) . '.php';
		if ( is_file( $file ) ) {
			require_once $file;
		}
	}

	spl_autoload_register( 'hds_vendor_autoload' );
}

PHP;
}

/**
 * Contents of vendor/README.md.
 *
 * @param string $version   Library version.
 * @param string $reference Git commit of the installed package.
 * @param int    $files     Number of vendored PHP files.
 * @return string
 */
function hds_pv_readme_source( string $version, string $reference, int $files ): string {
	$ref = '' !== $reference ? ' (commit `' . $reference . '`)' : '';
	return <<<MD
# Vendored third-party code

**Generated by `tools/prefix-vendor.php` - do not edit files here by hand.**

| Library | Version | License | Used for |
|---|---|---|---|
| [smalot/pdfparser](https://github.com/smalot/pdfparser) | {$version}{$ref} | LGPL-3.0 (`smalot/pdfparser/LICENSE.txt`) | Text extraction from PDF files (`HDS_Pdf_Extractor`) |

## Why vendored and prefixed

The plugin runs on shared hosting where Composer is not available, so the
runtime dependency is shipped inside the plugin. Every namespace
`Smalot\\PdfParser` was rewritten to `HDS_Vendor\\Smalot\\PdfParser` (also in
string literals the library uses to build class names dynamically), so this
copy can never clash with a different smalot/pdfparser version loaded by
another plugin or theme.

Only `src/` ({$files} PHP files) and the license are copied. Tests, samples
and dev files are not. `symfony/polyfill-mbstring` (a Composer dependency of
the library) is intentionally not included: the plugin requires the PHP
`mbstring` extension, and the library does not reference Symfony classes.

## Modifications (LGPL-3.0 section 4 / GPL-3.0 section 5a notice)

The vendored files are modified copies of smalot/pdfparser {$version}:

1. Namespace prefix `HDS_Vendor\\` added to every reference of `Smalot\\PdfParser`.
2. A direct-access guard (`if ( ! \\defined( 'ABSPATH' ) ) { exit; }`) and a
   one-line modification notice inserted after each namespace declaration.

No other code was changed. The original source is available at
https://github.com/smalot/pdfparser (tag v{$version}). LGPL-3.0 is a set of
additional permissions on top of the GNU GPL v3 (https://www.gnu.org/licenses/gpl-3.0.txt);
it is compatible with the plugin's GPL-2.0-or-later license (the combination
is distributable under GPL-3.0).

## Loading

`vendor/autoload.php` registers a PSR-4 autoloader for
`HDS_Vendor\\Smalot\\PdfParser\\` only. `HDS_Pdf_Extractor` requires it
lazily, so the library is loaded only when a PDF is processed.

## How to regenerate (developers only)

```sh
composer install            # installs dev deps into .dev/vendor (smalot/pdfparser {$version} pinned)
php tools/prefix-vendor.php # rewrites vendor/smalot/pdfparser, vendor/autoload.php, vendor/README.md
```

The script deletes and recreates `vendor/smalot/pdfparser/`, verifies that no
un-prefixed `Smalot\\PdfParser` reference and no Symfony reference remains,
and runs `php -l` on every generated file (skip with `--no-lint`).

MD;
}

// ---------------------------------------------------------------------------
// Main.
// ---------------------------------------------------------------------------

$hds_pv_root   = dirname( __DIR__ );
$hds_pv_lint   = ! in_array( '--no-lint', $argv, true );
$hds_pv_source = $hds_pv_root . '/.dev/vendor/smalot/pdfparser';
$hds_pv_vendor = $hds_pv_root . '/vendor';
$hds_pv_target = $hds_pv_vendor . '/smalot/pdfparser';

if ( ! is_dir( $hds_pv_source . '/src/Smalot/PdfParser' ) ) {
	hds_pv_fail( 'smalot/pdfparser not found in .dev/vendor - run `composer install` first.' );
}

// Installed version (informational, warn on mismatch).
$hds_pv_version   = 'unknown';
$hds_pv_reference = '';
$hds_pv_installed = $hds_pv_root . '/.dev/vendor/composer/installed.json';
if ( is_readable( $hds_pv_installed ) ) {
	$hds_pv_json     = json_decode( (string) file_get_contents( $hds_pv_installed ), true );
	$hds_pv_packages = isset( $hds_pv_json['packages'] ) ? $hds_pv_json['packages'] : ( is_array( $hds_pv_json ) ? $hds_pv_json : array() );
	foreach ( $hds_pv_packages as $hds_pv_package ) {
		if ( isset( $hds_pv_package['name'] ) && 'smalot/pdfparser' === $hds_pv_package['name'] ) {
			$hds_pv_version   = ltrim( (string) $hds_pv_package['version'], 'v' );
			$hds_pv_reference = isset( $hds_pv_package['dist']['reference'] ) ? (string) $hds_pv_package['dist']['reference'] : '';
		}
	}
}
if ( HDS_PV_VERSION !== $hds_pv_version ) {
	fwrite( STDERR, 'prefix-vendor: WARNING: expected smalot/pdfparser ' . HDS_PV_VERSION . ', found ' . $hds_pv_version . PHP_EOL );
}

// Clean the target (only vendor/smalot/pdfparser).
if ( ! is_dir( $hds_pv_vendor . '/smalot' ) && ! mkdir( $hds_pv_vendor . '/smalot', 0755, true ) ) {
	hds_pv_fail( 'cannot create ' . $hds_pv_vendor . '/smalot' );
}
hds_pv_rmdir( $hds_pv_target, (string) realpath( $hds_pv_vendor . '/smalot' ) );

// Copy + rewrite.
$hds_pv_src_root = $hds_pv_source . '/src';
$hds_pv_files    = array();
$hds_pv_iterator = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $hds_pv_src_root, FilesystemIterator::SKIP_DOTS ) );
foreach ( $hds_pv_iterator as $hds_pv_file ) {
	if ( ! $hds_pv_file->isFile() || 'php' !== strtolower( $hds_pv_file->getExtension() ) ) {
		continue;
	}
	$hds_pv_files[] = substr( $hds_pv_file->getPathname(), strlen( $hds_pv_src_root ) + 1 );
}
sort( $hds_pv_files );
if ( ! $hds_pv_files ) {
	hds_pv_fail( 'no PHP files found in ' . $hds_pv_src_root );
}

$hds_pv_written = array();
foreach ( $hds_pv_files as $hds_pv_relative ) {
	$hds_pv_code = (string) file_get_contents( $hds_pv_src_root . '/' . $hds_pv_relative );
	if ( preg_match( '/Symfony\\\\/i', $hds_pv_code ) ) {
		hds_pv_fail( $hds_pv_relative . ' references Symfony classes; the polyfill is not vendored.' );
	}
	$hds_pv_code = hds_pv_prefix( $hds_pv_code );
	$hds_pv_code = hds_pv_guard( $hds_pv_code, $hds_pv_relative );

	// Nothing un-prefixed may remain.
	if ( preg_match( '/Smalot\\\\+PdfParser/', str_replace( array( HDS_PV_PREFIX . '\\\\Smalot', HDS_PV_PREFIX . '\\Smalot' ), '', $hds_pv_code ) ) ) {
		hds_pv_fail( 'un-prefixed Smalot\\PdfParser reference left in ' . $hds_pv_relative );
	}

	$hds_pv_out = $hds_pv_target . '/src/' . $hds_pv_relative;
	if ( ! is_dir( dirname( $hds_pv_out ) ) && ! mkdir( dirname( $hds_pv_out ), 0755, true ) ) {
		hds_pv_fail( 'cannot create ' . dirname( $hds_pv_out ) );
	}
	if ( false === file_put_contents( $hds_pv_out, $hds_pv_code ) ) {
		hds_pv_fail( 'cannot write ' . $hds_pv_out );
	}
	$hds_pv_written[] = $hds_pv_out;
}

if ( ! copy( $hds_pv_source . '/LICENSE.txt', $hds_pv_target . '/LICENSE.txt' ) ) {
	hds_pv_fail( 'cannot copy LICENSE.txt' );
}

$hds_pv_autoload = $hds_pv_vendor . '/autoload.php';
file_put_contents( $hds_pv_autoload, hds_pv_autoload_source() );
$hds_pv_written[] = $hds_pv_autoload;
file_put_contents( $hds_pv_vendor . '/README.md', hds_pv_readme_source( $hds_pv_version, $hds_pv_reference, count( $hds_pv_files ) ) );

hds_pv_say( sprintf( 'Vendored smalot/pdfparser %s: %d PHP files -> vendor/smalot/pdfparser/src (namespace %s\\Smalot\\PdfParser).', $hds_pv_version, count( $hds_pv_files ), HDS_PV_PREFIX ) );

// Lint (dev machine only).
if ( $hds_pv_lint ) {
	$hds_pv_errors = 0;
	foreach ( $hds_pv_written as $hds_pv_path ) {
		$hds_pv_output = array();
		$hds_pv_status = 0;
		exec( escapeshellarg( PHP_BINARY ) . ' -l ' . escapeshellarg( $hds_pv_path ) . ' 2>&1', $hds_pv_output, $hds_pv_status ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions -- Dev-only CLI tool.
		if ( 0 !== $hds_pv_status ) {
			$hds_pv_errors++;
			fwrite( STDERR, implode( PHP_EOL, $hds_pv_output ) . PHP_EOL );
		}
	}
	if ( $hds_pv_errors ) {
		hds_pv_fail( $hds_pv_errors . ' file(s) failed php -l' );
	}
	hds_pv_say( sprintf( 'php -l (%s): %d files OK.', PHP_VERSION, count( $hds_pv_written ) ) );
}

hds_pv_say( 'Done. Wrote vendor/autoload.php and vendor/README.md.' );
